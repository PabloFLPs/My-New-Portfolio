/**
 * The portfolio's version, computed from the git history, so anyone can check it for any commit. Same scheme as
 * Marksage's `scripts/version.ts`.
 *
 *   node scripts/version.ts                      # version of HEAD
 *   node scripts/version.ts --commit <ref>       # version of any commit
 *   node scripts/version.ts --list               # every commit that changed the version
 *   node scripts/version.ts --next "<message>"   # before committing: write package.json, package-lock.json and
 *                                                #   CHANGELOG.md as that commit will be
 *   node scripts/version.ts --check              # those three match HEAD
 *
 * The rule (adopted 2026-11-12; earlier 3.x versions were assigned retroactively from the log):
 *   - `feat` → minor (patch back to 0) · `fix`, `perf` → patch · anything else (docs, chore, test, ci, refactor, or
 *     a subject that isn't a conventional commit, like every 2022 commit) → no change;
 *   - majors only at the commits in MAJORS, the portfolio's generations. 1.x lives in another repository.
 * Dates are commit dates in America/Sao_Paulo.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("..", import.meta.url).pathname;
const REPO = "https://github.com/PabloFLPs/My-New-Portfolio";

/** The first generation predates this repository. */
const FIRST_GENERATION = {
  what: "My-Portfolio-Page, the first portfolio (2021)",
  url: "https://github.com/PabloFLPs/My-Portfolio-Page",
};

export const MAJORS: Record<string, { major: number; what: string }> = {
  "56fc17e": { major: 2, what: "My-New-Portfolio, the Create React App portfolio (2022)" },
  "1bbbbaa": { major: 3, what: "the editorial rebuild on Next.js, in English and Portuguese (2026)" },
};

export type Row = { hash: string; date: string; subject: string };

export type Version = Row & {
  version: string;
  /** Whether this commit changed the version (feat / fix / perf / a major). */
  bumps: boolean;
};

/** What a commit subject does to the version. */
export function bumpOf(subject: string): "minor" | "patch" | null {
  const type = /^([a-z]+)(\([^)]*\))?!?:/.exec(subject)?.[1];
  if (type === "feat") return "minor";
  if (type === "fix" || type === "perf") return "patch";
  return null;
}

/** The version each commit produced, oldest first. */
export function versionsOf(rows: Row[], majors = MAJORS): Version[] {
  let [major, minor, patch] = [1, 0, 0];
  return rows.map((row) => {
    const generation = Object.entries(majors).find(([hash]) => row.hash.startsWith(hash))?.[1];
    const bump = bumpOf(row.subject);
    if (generation) [major, minor, patch] = [generation.major, 0, 0];
    else if (bump === "minor") [minor, patch] = [minor + 1, 0];
    else if (bump === "patch") patch++;
    return { ...row, version: `${major}.${minor}.${patch}`, bumps: Boolean(generation) || bump !== null };
  });
}

function git(...args: string[]): string {
  return execFileSync("git", args, {
    cwd: ROOT,
    encoding: "utf8",
    env: { ...process.env, TZ: "America/Sao_Paulo" },
  });
}

/** Every commit up to `ref`, oldest first; `next` adds the commit about to be made. */
export function history(ref = "HEAD", next?: string): Version[] {
  const rows: Row[] = git("log", "--reverse", "--format=%H%x09%ad%x09%s", "--date=format-local:%Y-%m-%d", ref)
    .split("\n")
    .filter(Boolean)
    .map((line) => {
      const [hash = "", date = "", subject = ""] = line.split("\t");
      return { hash, date, subject };
    });
  if (next) {
    const today = new Date().toLocaleDateString("sv-SE", { timeZone: "America/Sao_Paulo" });
    rows.push({ hash: "(this commit)", date: today, subject: next });
  }
  return versionsOf(rows);
}

export function changelog(versions: Version[]): string {
  const out = [
    "# Changelog",
    "",
    "Every version of the portfolio and the commit that made it, newest first — generated by `scripts/version.ts`",
    "from the git history (`npm run version:check` verifies this file). `feat` → minor, `fix` / `perf` → patch, other",
    "commits don’t change the version; majors mark the portfolio’s generations. **3.x versions before 3.17.0 were",
    "assigned retroactively on 2026-11-12** with this same rule; the commits are unchanged. The 2022 commits weren’t",
    "conventional commits, so 2.x stayed at 2.0.0. Dates: America/Sao_Paulo.",
    "",
  ];
  const shown = versions.filter((v) => v.bumps);
  for (const generation of Object.values(MAJORS).sort((a, b) => b.major - a.major)) {
    const inMajor = shown.filter((v) => v.version.startsWith(`${generation.major}.`)).reverse();
    out.push(`## ${generation.major}.x — ${generation.what}`, "");
    for (const v of inMajor) {
      const hash = v.hash.startsWith("(") ? v.hash : v.hash.slice(0, 7);
      out.push(`- **${v.version}** · ${v.date} · [\`${hash}\`](${REPO}/commit/${hash}) · ${v.subject}`);
    }
    out.push("");
  }
  out.push(`## 1.x — ${FIRST_GENERATION.what}`, "", `A separate repository: ${FIRST_GENERATION.url}`, "");
  return out.join("\n");
}

const pkgPath = `${ROOT}package.json`;
const lockPath = `${ROOT}package-lock.json`;
const logPath = `${ROOT}CHANGELOG.md`;

type Lock = { version?: string; packages?: Record<string, { version?: string }> };
const lockVersions = (lock: Lock) => [lock.version, lock.packages?.[""]?.version];

/** npm repeats the version twice in the lockfile and rewrites it on install, so keep both in step. */
function writeLockVersion(version: string) {
  const lock = JSON.parse(readFileSync(lockPath, "utf8")) as Lock;
  if (lockVersions(lock).every((v) => v === version)) return;
  lock.version = version;
  const root = lock.packages?.[""];
  if (root) root.version = version;
  writeFileSync(lockPath, JSON.stringify(lock, null, 2) + "\n");
}

function flag(name: string): string | undefined {
  const index = process.argv.indexOf(name);
  return index === -1 ? undefined : process.argv[index + 1];
}

function main() {
  if (process.argv.includes("--list")) {
    for (const v of history().filter((x) => x.bumps)) {
      console.log(`${v.version.padEnd(8)} ${v.date} ${v.hash.slice(0, 7)} ${v.subject}`);
    }
    return;
  }

  if (process.argv.includes("--next")) {
    const message = flag("--next");
    if (!message) throw new Error('--next needs the commit message: npm run version:next -- "<message>"');
    const versions = history("HEAD", message.split("\n")[0]);
    const now = versions.at(-1);
    if (!now) throw new Error("No history");
    writeFileSync(
      pkgPath,
      readFileSync(pkgPath, "utf8").replace(/"version": "[^"]*"/, `"version": "${now.version}"`),
    );
    writeLockVersion(now.version);
    writeFileSync(logPath, changelog(versions));
    console.log(
      `${now.bumps ? "version" : "unchanged"}: ${now.version} — package.json, package-lock.json and CHANGELOG.md written (commit them with it)`,
    );
    return;
  }

  if (process.argv.includes("--check")) {
    const versions = history();
    const head = versions.at(-1);
    if (!head) throw new Error("No history");
    const pkgVersion = (JSON.parse(readFileSync(pkgPath, "utf8")) as { version: string }).version;
    // The commit that made a version can't know its own hash: the changelog lists it as "(this commit)".
    const want = changelog(versions);
    const have = readFileSync(logPath, "utf8").replaceAll("(this commit)", head.hash.slice(0, 7));
    const problems = [
      ...(pkgVersion === head.version
        ? []
        : [`package.json says ${pkgVersion}, the history says ${head.version}`]),
      ...lockVersions(JSON.parse(readFileSync(lockPath, "utf8")) as Lock)
        .filter((v) => v !== head.version)
        .map((v) => `package-lock.json says ${v}, the history says ${head.version}`),
      ...(have === want
        ? []
        : ['CHANGELOG.md differs from the history — run version:next "<message>" before committing']),
    ];
    console.log(problems.length ? problems.join("\n") : `ok: ${head.version} (${head.hash.slice(0, 7)})`);
    process.exit(problems.length ? 1 : 0);
  }

  const versions = history(flag("--commit") ?? "HEAD");
  console.log(versions.at(-1)?.version);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
